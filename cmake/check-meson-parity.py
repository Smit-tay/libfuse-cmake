#!/usr/bin/env python3
"""Check that the CMake build of this fork still produces what meson does.

Builds the source tree twice - once with meson, once with CMake - and
compares:

  1. the generated fuse_config.h and libfuse_config.h
  2. the compile flags of every translation unit
  3. the set of programs and libraries built (what test/run-tests.py uses)
  4. libfuse3.so: SONAME, NEEDED and the exported symbol versions
  5. a DESTDIR install: paths, modes and symlinks, plus the content of every
     non-ELF file and the dynamic section of every ELF file
  6. optionally (--tests / --tests-as-root) the result of every test case

and that the CMake build compiles without a single warning. Exits non-zero
if anything differs. Only the standard library is needed, plus meson, ninja,
cmake, readelf and nm.

Run it after porting an upstream meson.build change to CMake; see
cmake/README.md.
"""

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SOURCE_DIR = Path(__file__).resolve().parent.parent

# Flags that are expected to differ, and why.
IGNORED_FLAGS = {
    # FindThreads adds nothing when pthreads live in libc (glibc >= 2.34);
    # the only thing -pthread would still define is _REENTRANT, which both
    # builds pass explicitly.
    '-pthread',
    # meson-only precompiled-header warning, and CMake's export macro for
    # shared library targets; neither changes the code.
    '-Winvalid-pch',
    '-Dfuse3_EXPORTS',
    # Deliberate divergence: this fork fixes these warnings in the code
    # instead of suppressing them (see CMakeLists.txt).
    '-Wno-sign-compare',
    '-Wno-unused-result',
}

# Generated headers start with a 4 line "Autogenerated by the <X> build
# system" banner that is allowed to differ.
GENERATED_HEADERS = ('fuse_config.h', 'libfuse_config.h')
BANNER_LINES = 4

TEST_LINE_RE = re.compile(r'^\+\s+[0-9.]+s (PASS|FAIL|SKIP)\s+(\S+)')


class Report:
    def __init__(self):
        self.failures = 0

    def section(self, title):
        print(f'\n== {title}')

    def ok(self, msg):
        print(f'   ok    {msg}')

    def fail(self, msg, details=()):
        self.failures += 1
        print(f'   FAIL  {msg}')
        for line in list(details)[:40]:
            print(f'           {line}')


def run(cmd, log, env=None, check=True, cwd=None):
    with open(log, 'w') as fh:
        proc = subprocess.run(cmd, stdout=fh, stderr=subprocess.STDOUT,
                              env=env, cwd=cwd)
    if check and proc.returncode:
        sys.exit(f'{" ".join(map(str, cmd))} failed (exit {proc.returncode}),'
                 f' see {log}')
    return proc.returncode


def strip_banner(path):
    return path.read_text().splitlines()[BANNER_LINES:]


def compile_flags(db_path):
    """{source path relative to SOURCE_DIR: sorted list of flag sets}"""
    result = {}
    for entry in json.loads(db_path.read_text()):
        args = entry.get('arguments') or shlex.split(entry['command'])
        src = Path(entry['directory'], entry['file']).resolve()
        try:
            src = src.relative_to(SOURCE_DIR)
        except ValueError:
            continue                    # generated or system file
        flags, skip = set(), False
        for arg in args[1:]:
            if skip:
                skip = False
                continue
            if arg in ('-o', '-MF', '-MQ', '-MT'):
                skip = True
                continue
            if (arg == '-c' or arg.startswith(('-I', '-M', '-fdiagnostics-color'))
                    or arg in IGNORED_FLAGS or arg.endswith(('.c', '.cc'))):
                continue
            flags.add(arg)
        result.setdefault(str(src), []).append(tuple(sorted(flags)))
    return {src: sorted(sets) for src, sets in result.items()}


def built_programs(build_dir, is_meson):
    """Executables and shared objects in the build tree, relative paths."""
    found = set()
    for path in build_dir.rglob('*'):
        rel = path.relative_to(build_dir)
        parts = rel.parts
        if any(p == 'CMakeFiles' or p.endswith('.p') or p.startswith('meson-')
               for p in parts):
            continue
        if path.is_file() and not path.is_symlink() and os.access(path, os.X_OK):
            if path.suffix in ('.py', '.sh'):
                continue
            found.add(str(rel))
    return found


def is_elf(path):
    with open(path, 'rb') as fh:
        return fh.read(4) == b'\x7fELF'


def dynamic_section(path):
    out = subprocess.run(['readelf', '-dW', str(path)], capture_output=True,
                         text=True, check=True).stdout
    keep = ('NEEDED', 'SONAME', 'RPATH', 'RUNPATH')
    return sorted(line.split(None, 1)[1] for line in out.splitlines()
                  if any(f'({k})' in line for k in keep))


def exported_symbols(path):
    out = subprocess.run(['nm', '-D', '--defined-only', str(path)],
                         capture_output=True, text=True, check=True).stdout
    return sorted(line.split()[-1] for line in out.splitlines() if line.strip())


def install_tree(root):
    """{relative path: (type, mode, symlink target)}"""
    tree = {}
    for path in sorted(root.rglob('*')):
        rel = str(path.relative_to(root))
        st = path.lstat()
        if path.is_symlink():
            tree[rel] = ('link', oct(st.st_mode & 0o7777), os.readlink(path))
        elif path.is_file():
            tree[rel] = ('file', oct(st.st_mode & 0o7777), '')
    return tree


def test_results(log):
    results = {}
    for line in Path(log).read_text().splitlines():
        hit = TEST_LINE_RE.match(line)
        if hit:
            results[hit.group(2)] = hit.group(1)
    return results


def diff_lines(a, b):
    import difflib
    return [l for l in difflib.unified_diff(a, b, 'meson', 'cmake', lineterm='')][2:]


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--work-dir', type=Path,
                        help='where to build (default: a new temporary directory)')
    parser.add_argument('--prefix', default='/usr/local',
                        help='install prefix for both builds (default: /usr/local)')
    parser.add_argument('--cc', help='C compiler for both builds (default: cc)')
    parser.add_argument('--cxx', help='C++ compiler for both builds')
    parser.add_argument('--meson-opt', action='append', default=[], metavar='OPT',
                        help='extra meson option, e.g. enable-custom-io=true; repeatable')
    parser.add_argument('--cmake-opt', action='append', default=[], metavar='OPT',
                        help='matching CMake option, e.g. OPTION_ENABLE_CUSTOM_IO=ON; repeatable')
    parser.add_argument('--tests', action='store_true',
                        help='also run test/run-tests.py on both builds and compare results')
    parser.add_argument('--tests-as-root', action='store_true',
                        help='like --tests, but run the suite through sudo')
    parser.add_argument('-j', '--jobs', type=int, default=os.cpu_count() // 2 or 1,
                        help='parallel test jobs')
    parser.add_argument('--keep', action='store_true',
                        help='keep the work directory of a temporary run')
    args = parser.parse_args()

    for tool in ('meson', 'ninja', 'cmake', 'readelf', 'nm'):
        if not shutil.which(tool):
            sys.exit(f'{tool} not found')

    temp = args.work_dir is None
    work = Path(tempfile.mkdtemp(prefix='fuse-parity-')) if temp else args.work_dir.resolve()
    work.mkdir(parents=True, exist_ok=True)
    mdir, cdir = work / 'meson', work / 'cmake'
    for d in (mdir, cdir, work / 'meson-dest', work / 'cmake-dest'):
        shutil.rmtree(d, ignore_errors=True)
    print(f'work directory: {work}')

    env = dict(os.environ)
    if args.cc:
        env['CC'] = args.cc
    if args.cxx:
        env['CXX'] = args.cxx

    # useroot off: the setuid step needs root and is the same script for both.
    run(['meson', 'setup', str(mdir), str(SOURCE_DIR), f'-Dprefix={args.prefix}',
         '-Duseroot=false'] + [f'-D{o}' for o in args.meson_opt],
        work / 'meson-setup.log', env)
    run(['cmake', '-S', str(SOURCE_DIR), '-B', str(cdir), '-G', 'Ninja',
         f'-DCMAKE_INSTALL_PREFIX={args.prefix}', '-DOPTION_USEROOT=OFF',
         '-DCMAKE_EXPORT_COMPILE_COMMANDS=ON'] + [f'-D{o}' for o in args.cmake_opt],
        work / 'cmake-setup.log', env)
    run(['ninja', '-C', str(mdir)], work / 'meson-build.log', env)
    run(['ninja', '-C', str(cdir)], work / 'cmake-build.log', env)

    rep = Report()

    rep.section('Warnings')
    for name in ('meson', 'cmake'):
        lines = [l for l in (work / f'{name}-build.log').read_text().splitlines()
                 if 'warning:' in l]
        if name == 'meson':
            print(f'   info  meson: {len(lines)} warnings (built with upstream\'s suppressions)')
        elif lines:
            rep.fail(f'cmake: {len(lines)} warnings', lines)
        else:
            rep.ok('cmake: 0 warnings')

    rep.section('Generated headers')
    for header in GENERATED_HEADERS:
        a, b = strip_banner(mdir / header), strip_banner(cdir / header)
        if a == b:
            rep.ok(header)
        else:
            rep.fail(header, diff_lines(a, b))

    rep.section('Compile flags per translation unit')
    mflags = compile_flags(mdir / 'compile_commands.json')
    cflags = compile_flags(cdir / 'compile_commands.json')
    bad = []
    for src in sorted(set(mflags) | set(cflags)):
        m, c = mflags.get(src, []), cflags.get(src, [])
        if m != c:
            mall = set().union(*m) if m else set()
            call = set().union(*c) if c else set()
            bad.append(f'{src}: compiled {len(m)}x/{len(c)}x, '
                       f'meson-only {sorted(mall - call)}, cmake-only {sorted(call - mall)}')
    if bad:
        rep.fail(f'{len(bad)} of {len(set(mflags) | set(cflags))} sources differ', bad)
    else:
        rep.ok(f'{len(mflags)} sources compiled with the same flags')

    rep.section('Programs and libraries built')
    mprogs, cprogs = built_programs(mdir, True), built_programs(cdir, False)
    if mprogs == cprogs:
        rep.ok(f'{len(mprogs)} identical')
    else:
        rep.fail('different sets',
                 [f'meson only: {p}' for p in sorted(mprogs - cprogs)] +
                 [f'cmake only: {p}' for p in sorted(cprogs - mprogs)])

    rep.section('libfuse3.so')
    mlib, clib = mdir / 'lib' / 'libfuse3.so.4', cdir / 'lib' / 'libfuse3.so.4'
    if not clib.exists():
        rep.fail('cmake build has no lib/libfuse3.so.4')
    else:
        for what, fn in (('SONAME/NEEDED', dynamic_section),
                         ('exported symbols and versions', exported_symbols)):
            a, b = fn(mlib), fn(clib)
            if a == b:
                rep.ok(f'{what} ({len(a)})' if what.startswith('exported') else what)
            else:
                rep.fail(what, diff_lines(a, b))

    rep.section(f'Install (prefix {args.prefix}, DESTDIR)')
    menv, cenv = dict(env, DESTDIR=str(work / 'meson-dest')), dict(env, DESTDIR=str(work / 'cmake-dest'))
    run(['meson', 'install', '-C', str(mdir), '--no-rebuild'], work / 'meson-install.log', menv)
    run(['cmake', '--install', str(cdir)], work / 'cmake-install.log', cenv)
    mtree, ctree = install_tree(work / 'meson-dest'), install_tree(work / 'cmake-dest')
    if mtree == ctree:
        rep.ok(f'{len(mtree)} paths: same types, modes and symlink targets')
    else:
        details = []
        for p in sorted(set(mtree) | set(ctree)):
            if mtree.get(p) != ctree.get(p):
                details.append(f'{p}: meson {mtree.get(p)} cmake {ctree.get(p)}')
        rep.fail('install trees differ', details)
    content_bad = []
    for rel, (kind, _, _) in sorted(mtree.items()):
        if kind != 'file' or ctree.get(rel, ('',))[0] != 'file':
            continue
        mp, cp = work / 'meson-dest' / rel, work / 'cmake-dest' / rel
        if is_elf(mp):
            # Code differs in debug info and layout; what is checked is how
            # the dynamic linker sees the file.
            if dynamic_section(mp) != dynamic_section(cp):
                content_bad.append(f'{rel}: dynamic section differs')
        elif Path(rel).name in GENERATED_HEADERS:
            if strip_banner(mp) != strip_banner(cp):
                content_bad.append(f'{rel}: content differs')
        elif mp.read_bytes() != cp.read_bytes():
            content_bad.append(f'{rel}: content differs')
    if content_bad:
        rep.fail('installed file contents differ', content_bad)
    else:
        rep.ok('installed file contents match (ELF files: dynamic section)')

    if args.tests or args.tests_as_root:
        who = 'root' if args.tests_as_root else 'unprivileged'
        rep.section(f'Test suite ({who})')
        results = {}
        for name, bdir in (('meson', mdir), ('cmake', cdir)):
            cmd = [str(SOURCE_DIR / 'test' / 'run-tests.py'), '--build-dir', str(bdir),
                   '--run-dir', str(work / f'run-{name}'), '-j', str(args.jobs)]
            if args.tests_as_root:
                cmd = ['sudo'] + cmd
            log = work / f'{name}-tests.log'
            rc = run(cmd, log, env, check=False)
            results[name] = test_results(log)
            summary = [l for l in log.read_text().splitlines() if re.match(r'^\d+ tests:', l)]
            print(f'   info  {name}: {summary[0] if summary else "no summary"} (exit {rc})')
        if args.tests_as_root:
            subprocess.run(['sudo', 'chown', '-R', f'{os.getuid()}:{os.getgid()}', str(work)],
                           check=False)
        m, c = results['meson'], results['cmake']
        if not c:
            rep.fail('no test results from the cmake build')
        elif m == c:
            rep.ok(f'{len(c)} tests, identical per-test results')
        else:
            rep.fail('per-test results differ',
                     [f'{t}: meson {m.get(t)} cmake {c.get(t)}'
                      for t in sorted(set(m) | set(c)) if m.get(t) != c.get(t)])

    print()
    if rep.failures:
        print(f'{rep.failures} check(s) FAILED; logs in {work}')
    else:
        print('CMake build matches meson.')
        if temp and not args.keep:
            shutil.rmtree(work, ignore_errors=True)
    return 1 if rep.failures else 0


if __name__ == '__main__':
    sys.exit(main())
